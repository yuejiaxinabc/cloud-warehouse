/** 把一个字符转成单条 path（像素级，无文本节点） */
export function glyphPath(ch: string): string | null {
  const rows = GLYPHS[ch.toUpperCase()];
  if (!rows) return null;
  let d = "";
  for (let y = 0; y < rows.length; y++) {
    for (let x = 0; x < rows[y].length; x++) {
      if (rows[y][x] === "1") {
        // 每个像素一个 1x1 方块，坐标单位 = 1 像素
        d += `M${x} ${y}h1v1h-1z`;
      }
    }
  }
  return d;
}

